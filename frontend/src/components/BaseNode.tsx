export interface BaseNodeProps<T extends AgentNode = AgentNode> extends NodeProps<T> {
    children?: React.ReactNode;
    showDeleteButton?: boolean;
    classNames: string;
}

const BaseNode = <T extends AgentNode>({
                                           id,
                                           data,
                                           children,
                                           showDeleteButton = true,
                                           classNames = '',
                                       }: BaseNodeProps<T>) => {
    const [isModalOpen, setIsModalOpen] = useState<boolean>(false);
    const handleOpenModal = useCallback(() => setIsModalOpen(true), []);
    const handleCloseModal = useCallback(() => setIsModalOpen(false), []);
    return (
        <div className="relative">
            {showDeleteButton && (
                <button
                    className="absolute right-1 top-1"
                >
                    <svg
                        xmlns="http://www.w3.org/2000/svg"
                        fill="none"
                        viewBox="0 0 24 24"
                        strokeWidth="1.5"
                        stroke="currentColor"
                        className="size-4"
                    >
                        <path
                            strokeLinecap="round"
                            strokeLinejoin="round"
                            d="M9.75 9.75l4.5 4.5m0-4.5-4.5 4.5M21 12a9 9 0 1 1-18 0 9 9 0 0 1 18 0Z"
                        />
                    </svg>
                </button>
            )}
            <div
                className={`${classNames} flex justify-center items-center border-2 
                ${data.status === "completed"
                    ? "border-emerald-600"
                    : data.status === "failed"
                        ? "border-red-600"
                        : data.status === "running"
                            ? "border-orange-300 opacity-50"
                            : "border-white"}`}
            >
                <div className="">
                    {getIcon(data.type)}
                </div>
            </div>

            {children}

            {data.status === "running" && (
                <div className="absolute inset-0 flex items-center justify-center">
                    <div
                        className="w-8 h-8 border-4 border-orange-300 border-t-transparent rounded-full animate-spin"></div>
                </div>
            )}
            <BaseModal id={id} isOpen={isModalOpen} onClose={handleCloseModal} data={data} />
        </div>
    );
};

export default BaseNode;